#!/usr/bin/env node
import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import {
  buildReverseForwardArgs,
  readOptionalTunnelPort,
} from './personal-computer-tunnel.mjs';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(SCRIPT_DIR, '..');

function printUsage() {
  console.log(`Usage:
  node scripts/personal-computer-agent.mjs \\
    --pairing-file /secure/path/personal-laptop.env \\
    --workspace /path/to/projects

Options:
  --pairing-file PATH   Pairing file generated by register-personal-computer.mjs
  --workspace PATH      Default workspace exposed by this Codex account
  --codex-home PATH     Codex home (default: CODEX_HOME or ~/.codex)
  --profile-id ID       Account id shown in code-ai
  --profile-label TEXT  Account label shown in code-ai
  --storage-root PATH   Private runtime data directory
  --codex-bin PATH      Codex executable (default: codex)
  --build               Build dist/ before starting
  --help,-h             Show help
`);
}

function readArgs(argv) {
  const options = {
    pairingFile: process.env.CODEX_REMOTE_PAIRING_FILE || '',
    workspace: os.homedir(),
    codexHome: process.env.CODEX_HOME || path.join(os.homedir(), '.codex'),
    profileId: '',
    profileLabel: '',
    storageRoot: '',
    codexBin: process.env.CODEX_BIN || 'codex',
    build: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    const value = () => {
      const next = argv[index + 1];
      if (typeof next !== 'string') throw new Error(`Missing value for ${argument}`);
      index += 1;
      return next;
    };
    switch (argument) {
      case '--pairing-file': options.pairingFile = path.resolve(value()); break;
      case '--workspace': options.workspace = path.resolve(value()); break;
      case '--codex-home': options.codexHome = path.resolve(value()); break;
      case '--profile-id': options.profileId = value().trim().toLowerCase(); break;
      case '--profile-label': options.profileLabel = value().trim(); break;
      case '--storage-root': options.storageRoot = path.resolve(value()); break;
      case '--codex-bin': options.codexBin = value().trim(); break;
      case '--build': options.build = true; break;
      case '--help':
      case '-h':
        printUsage();
        process.exit(0);
      default:
        throw new Error(`Unknown argument: ${argument}`);
    }
  }
  if (!options.pairingFile) throw new Error('--pairing-file is required');
  return options;
}

function parseEnv(raw) {
  const values = {};
  for (const rawLine of raw.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const separator = line.indexOf('=');
    if (separator < 1) continue;
    values[line.slice(0, separator).trim()] = line.slice(separator + 1);
  }
  return values;
}

function readPort(value, name) {
  const port = Number(String(value ?? '').trim());
  if (!Number.isInteger(port) || port < 1 || port > 65_535) {
    throw new Error(`${name} is missing or invalid in the pairing file`);
  }
  return port;
}

function waitForAgent(port, token, timeoutMs = 20_000) {
  const deadline = Date.now() + timeoutMs;
  return new Promise((resolve, reject) => {
    const attempt = () => {
      const request = http.request({
        hostname: '127.0.0.1',
        port,
        path: '/api/codex/remote-agent/health',
        method: 'GET',
        headers: { 'x-code-ai-remote-token': token },
        timeout: 1_500,
      }, (response) => {
        response.resume();
        if (response.statusCode === 200) {
          resolve();
          return;
        }
        retry(new Error(`Agent health returned HTTP ${response.statusCode}`));
      });
      request.once('timeout', () => request.destroy(new Error('Agent health timed out')));
      request.once('error', retry);
      request.end();
    };
    const retry = (error) => {
      if (Date.now() >= deadline) {
        reject(error);
        return;
      }
      setTimeout(attempt, 300);
    };
    attempt();
  });
}

function runBuild() {
  const result = spawnSync('npm', ['run', 'build'], {
    cwd: APP_ROOT,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    windowsHide: true,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Build failed with status ${result.status}`);
}

async function main() {
  const options = readArgs(process.argv.slice(2));
  const pairing = parseEnv(await readFile(options.pairingFile, 'utf8'));
  const hostId = pairing.CODEX_REMOTE_HOST_ID?.trim();
  const hostLabel = pairing.CODEX_REMOTE_HOST_LABEL?.trim() || os.hostname();
  const token = pairing.CODEX_REMOTE_AGENT_TOKEN?.trim();
  const controlTarget = pairing.CODEX_REMOTE_CONTROL_TARGET?.trim();
  const reversePort = readPort(pairing.CODEX_REMOTE_REVERSE_PORT, 'CODEX_REMOTE_REVERSE_PORT');
  const sidecarPort = readPort(pairing.CODEX_REMOTE_SIDECAR_PORT, 'CODEX_REMOTE_SIDECAR_PORT');
  const sshReversePort = readOptionalTunnelPort(
    pairing.CODEX_REMOTE_SSH_REVERSE_PORT,
    'CODEX_REMOTE_SSH_REVERSE_PORT'
  );
  const sshLocalPort = sshReversePort === null
    ? 22
    : readPort(
      pairing.CODEX_REMOTE_SSH_LOCAL_PORT || '22',
      'CODEX_REMOTE_SSH_LOCAL_PORT'
    );
  if (!hostId || !/^[a-z0-9][a-z0-9_-]{0,63}$/.test(hostId)) {
    throw new Error('CODEX_REMOTE_HOST_ID is missing or invalid in the pairing file');
  }
  if (!token || token.length < 24) {
    throw new Error('CODEX_REMOTE_AGENT_TOKEN is missing or too short in the pairing file');
  }
  if (!controlTarget || !/^[a-zA-Z0-9_.:@-]+$/.test(controlTarget)) {
    throw new Error('CODEX_REMOTE_CONTROL_TARGET is missing or invalid in the pairing file');
  }

  if (options.build) runBuild();
  const serverPath = path.join(APP_ROOT, 'dist', 'server.js');
  if (!existsSync(serverPath)) {
    throw new Error('dist/server.js is missing. Run npm run build or pass --build.');
  }

  const profileId = options.profileId || `${hostId}-codex`;
  const profiles = [{
    id: profileId,
    label: options.profileLabel || `${hostLabel} Codex`,
    provider: 'codex',
    codexHome: options.codexHome,
    workspaceCwd: options.workspace,
    defaultProfile: true,
  }];
  const storageRoot = options.storageRoot || path.join(os.homedir(), '.code-ai-remote', hostId);
  const childEnv = {
    ...process.env,
    NODE_ENV: 'production',
    HOST: '127.0.0.1',
    PORT: String(sidecarPort),
    CODEX_APP_ROOT: APP_ROOT,
    CODEX_STORAGE_ROOT: storageRoot,
    CODEX_UPLOAD_ROOT: path.join(storageRoot, 'uploads'),
    CODEX_QUEUE_ROOT: path.join(storageRoot, 'queue'),
    CODEX_LOG_ROOT: path.join(storageRoot, 'logs'),
    CODEX_OPEN_ACCESS: 'true',
    CODEX_ALLOW_ANY_PATHS: 'true',
    CODEX_PROFILES_JSON_BASE64: Buffer.from(JSON.stringify(profiles), 'utf8').toString('base64'),
    CODEX_BIN: options.codexBin,
    CODEX_REMOTE_AGENT_TOKEN: token,
    SESSION_SECRET: randomBytes(32).toString('hex'),
  };

  let stopping = false;
  let tunnel = null;
  const sidecar = spawn(process.execPath, [serverPath], {
    cwd: APP_ROOT,
    env: childEnv,
    stdio: 'inherit',
    windowsHide: true,
  });

  const stop = (exitCode = 0) => {
    if (stopping) return;
    stopping = true;
    if (tunnel && !tunnel.killed) tunnel.kill('SIGTERM');
    if (!sidecar.killed) sidecar.kill('SIGTERM');
    setTimeout(() => process.exit(exitCode), 250).unref();
  };
  process.once('SIGINT', () => stop(0));
  process.once('SIGTERM', () => stop(0));
  sidecar.once('error', (error) => {
    console.error(`Remote sidecar failed: ${error.message}`);
    stop(1);
  });
  sidecar.once('exit', (code, signal) => {
    if (!stopping) {
      console.error(`Remote sidecar stopped unexpectedly (${code ?? signal ?? 'unknown'})`);
      stop(code || 1);
    }
  });

  await waitForAgent(sidecarPort, token);
  console.log(`Remote sidecar is ready on 127.0.0.1:${sidecarPort}`);

  const reverseForwardArgs = buildReverseForwardArgs({
    apiReversePort: reversePort,
    sidecarPort,
    sshReversePort,
    sshLocalPort,
  });
  const startTunnel = () => {
    if (stopping) return;
    tunnel = spawn('ssh', [
      '-N',
      '-T',
      '-o', 'BatchMode=yes',
      '-o', 'ExitOnForwardFailure=yes',
      '-o', 'ServerAliveInterval=15',
      '-o', 'ServerAliveCountMax=3',
      ...reverseForwardArgs,
      controlTarget,
    ], {
      stdio: ['ignore', 'inherit', 'inherit'],
      windowsHide: true,
    });
    tunnel.once('error', (error) => {
      console.error(`Reverse SSH tunnel failed: ${error.message}`);
    });
    tunnel.once('exit', (code, signal) => {
      if (stopping) return;
      console.error(`Reverse SSH tunnel stopped (${code ?? signal ?? 'unknown'}); retrying in 3 seconds`);
      setTimeout(startTunnel, 3_000);
    });
  };

  startTunnel();
  console.log(`Reverse SSH tunnel requested on control-plane loopback port ${reversePort}`);
  if (sshReversePort !== null) {
    console.log(
      `Inbound SSH bridge requested on control-plane loopback port ${sshReversePort}`
    );
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
