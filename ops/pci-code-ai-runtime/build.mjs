import { execFileSync } from 'node:child_process';
import { cp, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
import { smoke } from './smoke.mjs';
import { copyOptions, assertContainedLinks } from './package-contract.mjs';
execFileSync('npm', ['ci', '--omit=dev', '--no-audit', '--no-fund'], {cwd:'payload', stdio:'inherit'});
const require = createRequire(path.resolve('payload/package.json'));
for (const module of ['node-pty','express','express-session','multer','ws','connect-pg-simple','pg','cors']) require(module);
const dynamicLibraries = execFileSync('ldd', [process.execPath], {encoding:'utf8'});
assert.ok(!dynamicLibraries.includes('libnode.so'), 'Node executable must be independently portable');
await mkdir('dist/app', {recursive:true});
await cp('payload/prebuilt', 'dist/app/dist', copyOptions);
await cp('payload/node_modules', 'dist/app/node_modules', copyOptions);
await cp('payload/package.json', 'dist/app/package.json');
await cp('payload/server', 'dist/app/server', copyOptions);
await cp('payload/skills', 'dist/app/skills', copyOptions);
await cp('payload/codex-vendor', 'dist/codex-vendor', copyOptions);
await mkdir('dist/bin', {recursive:true});
await cp(process.execPath, 'dist/bin/node');
await writeFile('dist/runtime-identity.json', JSON.stringify({nodeVersion:process.version,nodeAbi:process.versions.modules,codexVersion:'0.160.1',serverBuildId:'74ee3eaf-de92-4f53-be0b-c0a1e46fa1be'})+'\n');
const checks=await smoke({appRoot:path.resolve('dist/app'),codexBin:path.resolve('dist/codex-vendor/bin/codex'),nodeBinary:path.resolve('dist/bin/node')});
console.log(JSON.stringify({nativePty:true,...checks,...await assertContainedLinks('dist')}));
