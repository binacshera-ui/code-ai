import assert from 'node:assert/strict';
import { readFile, writeFile, rename, stat } from 'node:fs/promises';
const [id, action] = process.argv.slice(2);
assert.ok(['beam-10g', 'pci', 'ubuntu-gpu-lab'].includes(id));
assert.ok(['pause', 'resume'].includes(action));
const filename = '/root/projects/code-ai/.code-ai/remote-hosts.json';
const data = JSON.parse(await readFile(filename, 'utf8'));
const host = data.hosts.find(entry => entry.id === id);
assert.ok(host, 'Server registration missing');
assert.equal(host.enabled, action === 'pause', 'Server routing state changed');
host.enabled = action === 'resume';
const temporary = filename + '.draft-unblock-' + process.pid;
await writeFile(temporary, JSON.stringify(data, null, 2) + '\n', { mode: (await stat(filename)).mode & 0o777, flag: 'wx' });
await rename(temporary, filename);
console.log(JSON.stringify({ id, routingEnabled: host.enabled }));
