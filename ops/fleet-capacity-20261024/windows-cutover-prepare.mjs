import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
const [candidate,binary,binarySha]=process.argv.slice(2);
assert.equal(process.platform,'win32');
const root='C:/Users/showp/.code-ai/remote-agent',pairingFile=root+'/pairing.json';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
assert.equal(hash(await fs.readFile(binary)),binarySha);
const qfile='C:/Users/showp/.code-ai-remote/personal-windows-me/queue/state.json';
const rows=JSON.parse(await fs.readFile(qfile,'utf8')).items;
assert.ok(!rows.some(row=>['running','queued','cancelling'].includes(row.status)),'Windows has active work; wait');
const old=await fs.readFile(pairingFile,'utf8'),pairing=JSON.parse(old);assert.equal(pairing.id,'personal-windows-me');
const backup=await fs.mkdtemp(root+'/release-backup-20261024-');
await fs.writeFile(backup+'/pairing-before.json',old,{mode:0o600,flag:'wx'});await fs.copyFile(qfile,backup+'/queue-before.json',1);
const launcher=await fs.readFile(root+'/window-control/launch-hidden.vbs','utf8');
assert.ok(launcher.includes('releases\\20261008-v1'));
const next=launcher.replaceAll('20261008-v1',path.basename(candidate));
await fs.writeFile(candidate+'/launch-hidden.vbs',next,{flag:'wx'});
const updated={...pairing,codexBin:binary};
const originalRest={...pairing};delete originalRest.codexBin;const nextRest={...updated};delete nextRest.codexBin;
assert.deepEqual(nextRest,originalRest);
await fs.writeFile(pairingFile+'.capacity-tmp',JSON.stringify(updated,null,2)+'\n',{mode:0o600,flag:'wx'});
await fs.rename(pairingFile+'.capacity-tmp',pairingFile);
const report={prepared:true,candidate,backup,launcher:candidate+'/launch-hidden.vbs',codexBin:binary,credentialsUnchanged:true,queueWasIdle:true,originalQueueItems:rows.length};
await fs.writeFile(backup+'/cutover.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
