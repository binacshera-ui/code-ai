import {cp,mkdir,readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
await mkdir('dist',{recursive:true});
await cp('chrome-extension','dist/CODE-AI-Chrome-Extension',{recursive:true});
const panelPath='dist/CODE-AI-Chrome-Extension/panel.html';
const panel=await readFile(panelPath,'utf8');
assert.ok(panel.includes('content="http://127.0.0.1:4000"'));
await writeFile(panelPath,panel.replace('content="http://127.0.0.1:4000"','content="https://app-codex.bina-cshera.co.il"'));
const manifest=JSON.parse(await readFile('dist/CODE-AI-Chrome-Extension/manifest.json','utf8'));
assert.equal(manifest.version,'1.5.1');
const hashes={};
for(const name of await readdir('dist/CODE-AI-Chrome-Extension'))hashes[name]=createHash('sha256').update(await readFile('dist/CODE-AI-Chrome-Extension/'+name)).digest('hex');
await writeFile('dist/package-hashes.json',JSON.stringify({version:manifest.version,predecessor:'23711fe1-41fa-49b7-aac7-9c63ef7c3a6b',backendChanged:false,nativeWindowsVerification:'pending-on-new-computer',files:hashes},null,2)+'\n');
