import { execFileSync } from 'node:child_process';
import { cp,mkdir,mkdtemp,readFile,writeFile,copyFile,constants } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import assert from 'node:assert/strict';
const buildId=process.argv[2];assert.match(buildId,/^[a-f0-9-]{36}$/);
const imports='/mnt/hdd/code-ai-builds/chrome-profile-imports';
execFileSync('bina-build',['verify-import',buildId,'--import-root',imports],{stdio:'pipe'});
const source=path.join(imports,buildId,'artifact/dist/chrome-extension');
const stage=await mkdtemp('/mnt/hdd/code-ai-builds/chrome-150-qualified-');
const candidate=stage+'/CODE-AI-Chrome-Extension';
await cp(source,candidate,{recursive:true,verbatimSymlinks:true});
const panel=await readFile(candidate+'/panel.html','utf8');
assert.ok(panel.includes('content="http://127.0.0.1:4000"'));
await writeFile(candidate+'/panel.html',panel.replace('content="http://127.0.0.1:4000"','content="https://app-codex.bina-cshera.co.il"'));
const manifest=JSON.parse(await readFile(candidate+'/manifest.json','utf8'));assert.equal(manifest.version,'1.5.0');
const files=await import('node:fs/promises').then(fs=>fs.readdir(candidate));
const hashes={};for(const file of files)hashes[file]=createHash('sha256').update(await readFile(path.join(candidate,file))).digest('hex');
await writeFile(stage+'/package-hashes.json',JSON.stringify({buildId,version:'1.5.0',files:hashes},null,2)+'\n');
const zip=stage+'/CODE-AI-Chrome-Extension-1.5.0.zip';
execFileSync('zip',['-q','-r',zip,'CODE-AI-Chrome-Extension'],{cwd:stage,stdio:'pipe'});
const download='/root/projects/code-ai/.code-ai/uploads/CODE-AI-Chrome-Extension-1.5.0-'+buildId+'.zip';
await copyFile(zip,download,constants.COPYFILE_EXCL);
console.log(JSON.stringify({buildId,stage,candidate,download,zipSha256:createHash('sha256').update(await readFile(zip)).digest('hex'),backgroundSha256:hashes['background.js']}));
